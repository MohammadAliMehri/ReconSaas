package report

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/MohammadAliMehri/ReconSaas/internal/model"
)

const ToolVersion = "3.0.0"

// Generator compiles results and findings into structured JSON, Markdown, and individual category files.
type Generator struct {
	outputDir string
	target    string
	mode      model.Mode
}

// NewGenerator creates a new report Generator.
func NewGenerator(outputDir, target string, mode model.Mode) *Generator {
	return &Generator{
		outputDir: outputDir,
		target:    target,
		mode:      mode,
	}
}

// Generate compiles and writes all reports and artifacts.
func (g *Generator) Generate(results []*model.ModuleResult, allFindings []model.Finding) error {
	if err := os.MkdirAll(g.outputDir, 0750); err != nil {
		return err
	}
	_ = os.MkdirAll(filepath.Join(g.outputDir, "passive"), 0750)
	_ = os.MkdirAll(filepath.Join(g.outputDir, "active"), 0750)
	_ = os.MkdirAll(filepath.Join(g.outputDir, "analysis"), 0750)

	// Save individual module JSON files
	for _, res := range results {
		if res == nil {
			continue
		}
		subdir := "passive"
		switch res.Module {
		case "ports", "tech", "headers", "dirs", "endpoints", "bypass":
			subdir = "active"
		case "rank", "report":
			subdir = "analysis"
		}

		modPath := filepath.Join(g.outputDir, subdir, fmt.Sprintf("%s.json", res.Module))
		_ = saveJSON(res, modPath)

		// Specific text file exports matching v2
		if res.Module == "certs" {
			if rawSubs, ok := res.Data["subdomains"].([]string); ok && len(rawSubs) > 0 {
				txtPath := filepath.Join(g.outputDir, "passive", "subdomains.txt")
				_ = os.WriteFile(txtPath, []byte(strings.Join(rawSubs, "\n")), 0600)
			}
		}

		if res.Module == "wayback" {
			if rawURLs, ok := res.Data["urls"].([]map[string]string); ok && len(rawURLs) > 0 {
				var lines []string
				for _, entry := range rawURLs {
					if u, exists := entry["url"]; exists && u != "" {
						lines = append(lines, u)
					}
				}
				if len(lines) > 0 {
					txtPath := filepath.Join(g.outputDir, "passive", "wayback_urls.txt")
					_ = os.WriteFile(txtPath, []byte(strings.Join(lines, "\n")), 0600)
				}
			}
		}
	}

	// Generate and save Markdown report
	mdReport := g.renderMarkdown(results, allFindings)
	if err := os.WriteFile(filepath.Join(g.outputDir, "report.md"), []byte(mdReport), 0600); err != nil {
		return err
	}

	// Generate and save JSON report
	jsonReport := g.renderJSON(results, allFindings)
	return saveJSON(jsonReport, filepath.Join(g.outputDir, "report.json"))
}

func (g *Generator) renderMarkdown(results []*model.ModuleResult, findings []model.Finding) string {
	now := time.Now().UTC().Format("2006-01-02 15:04:05 UTC")

	sevCounts := map[model.Severity]int{
		model.SeverityCritical: 0,
		model.SeverityHigh:     0,
		model.SeverityMedium:   0,
		model.SeverityLow:      0,
		model.SeverityInfo:     0,
	}

	for _, f := range findings {
		sevCounts[f.Severity]++
	}

	totalFindings := len(findings)

	var sb strings.Builder
	sb.WriteString("# ReconSaas Report\n\n")
	sb.WriteString(fmt.Sprintf("**Target:** `%s`  \n", g.target))
	sb.WriteString(fmt.Sprintf("**Mode:** %s  \n", strings.ToUpper(string(g.mode))))
	sb.WriteString(fmt.Sprintf("**Date:** %s  \n", now))
	sb.WriteString(fmt.Sprintf("**Generated by:** ReconSaas v%s\n\n", ToolVersion))
	sb.WriteString("---\n\n## Executive Summary\n\n")
	sb.WriteString("| Severity | Count |\n|----------|-------|\n")
	sb.WriteString(fmt.Sprintf("| 🔴 Critical | %d |\n", sevCounts[model.SeverityCritical]))
	sb.WriteString(fmt.Sprintf("| 🟠 High | %d |\n", sevCounts[model.SeverityHigh]))
	sb.WriteString(fmt.Sprintf("| 🟡 Medium | %d |\n", sevCounts[model.SeverityMedium]))
	sb.WriteString(fmt.Sprintf("| 🔵 Low | %d |\n", sevCounts[model.SeverityLow]))
	sb.WriteString(fmt.Sprintf("| ⚪ Info | %d |\n", sevCounts[model.SeverityInfo]))
	sb.WriteString(fmt.Sprintf("| **Total** | **%d** |\n\n", totalFindings))
	sb.WriteString("---\n\n## Findings\n\n")

	// Sort findings by severity
	sevOrder := map[model.Severity]int{
		model.SeverityCritical: 0,
		model.SeverityHigh:     1,
		model.SeverityMedium:   2,
		model.SeverityLow:      3,
		model.SeverityInfo:     4,
	}

	sortedFindings := make([]model.Finding, len(findings))
	copy(sortedFindings, findings)
	sort.Slice(sortedFindings, func(i, j int) bool {
		return sevOrder[sortedFindings[i].Severity] < sevOrder[sortedFindings[j].Severity]
	})

	icons := map[model.Severity]string{
		model.SeverityCritical: "🔴",
		model.SeverityHigh:     "🟠",
		model.SeverityMedium:   "🟡",
		model.SeverityLow:      "🔵",
		model.SeverityInfo:     "⚪",
	}

	for i, f := range sortedFindings {
		icon := icons[f.Severity]
		if icon == "" {
			icon = "⚪"
		}
		sb.WriteString(fmt.Sprintf("### %s %d. [%s] %s\n\n", icon, i+1, strings.ToUpper(string(f.Severity)), f.Title))
		if f.Detail != "" {
			sb.WriteString(fmt.Sprintf("%s\n\n", f.Detail))
		}
		if len(f.Evidence) > 0 {
			sb.WriteString("**Evidence:**\n```json\n")
			evBytes, _ := json.MarshalIndent(f.Evidence, "", "  ")
			sb.WriteString(string(evBytes))
			sb.WriteString("\n```\n\n")
		}
	}

	// Subdomains section
	for _, res := range results {
		if res.Module == "certs" {
			if subs, ok := res.Data["subdomains"].([]string); ok && len(subs) > 0 {
				sb.WriteString(fmt.Sprintf("---\n\n## Subdomains (%d)\n\n```\n", len(subs)))
				for _, s := range subs {
					sb.WriteString(fmt.Sprintf("%s\n", s))
				}
				sb.WriteString("```\n\n")
			}
		}

		if res.Module == "ports" {
			if rawPorts, ok := res.Data["open_ports"]; ok {
				sb.WriteString("---\n\n## Open Ports\n\n")
				sb.WriteString("| Port | Service | Banner |\n|------|---------|--------|\n")
				if portBytes, err := json.Marshal(rawPorts); err == nil {
					var pList []struct {
						Port    int    `json:"port"`
						Service string `json:"service"`
						Banner  string `json:"banner,omitempty"`
					}
					if err := json.Unmarshal(portBytes, &pList); err == nil {
						for _, p := range pList {
							sb.WriteString(fmt.Sprintf("| %d | %s | %s |\n", p.Port, p.Service, p.Banner))
						}
					}
				}
				sb.WriteString("\n")
			}
		}

		if res.Module == "tech" {
			if techList, ok := res.Data["tech_names"].([]string); ok && len(techList) > 0 {
				sb.WriteString("---\n\n## Technology Stack\n\n")
				sb.WriteString(strings.Join(techList, ", "))
				sb.WriteString("\n\n")
			}
		}
	}

	sb.WriteString(fmt.Sprintf("\n---\n\n*Report generated by ReconSaas v%s on %s*\n", ToolVersion, now))
	return sb.String()
}

func (g *Generator) renderJSON(results []*model.ModuleResult, findings []model.Finding) map[string]interface{} {
	sevCounts := map[string]int{
		"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0,
	}
	for _, f := range findings {
		sevCounts[string(f.Severity)]++
	}

	moduleSummary := make(map[string]interface{})
	var subdomains []string
	var technologies []string
	var openPorts interface{}
	var rankedAssets interface{}

	for _, res := range results {
		if res == nil {
			continue
		}
		moduleSummary[res.Module] = map[string]interface{}{
			"findings_count": len(res.Findings),
			"duration_ms":    res.Duration.Milliseconds(),
			"errors":         res.Errors,
		}

		if res.Module == "certs" {
			if s, ok := res.Data["subdomains"].([]string); ok {
				subdomains = s
			}
		}
		if res.Module == "tech" {
			if t, ok := res.Data["tech_names"].([]string); ok {
				technologies = t
			}
		}
		if res.Module == "ports" {
			openPorts = res.Data["open_ports"]
		}
		if res.Module == "rank" {
			rankedAssets = res.Data["top_targets"]
		}
	}

	return map[string]interface{}{
		"metadata": map[string]interface{}{
			"tool":      "ReconSaas",
			"version":   ToolVersion,
			"target":    g.target,
			"mode":      string(g.mode),
			"timestamp": time.Now().UTC().Format(time.RFC3339),
		},
		"summary": map[string]interface{}{
			"total_findings": len(findings),
			"by_severity":    sevCounts,
		},
		"findings":      findings,
		"modules":       moduleSummary,
		"subdomains":    subdomains,
		"technologies":  technologies,
		"open_ports":    openPorts,
		"ranked_assets": rankedAssets,
	}
}

func saveJSON(v interface{}, filePath string) error {
	data, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filePath, data, 0600)
}

