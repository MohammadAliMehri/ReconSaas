"""
Report Generator — Creates Markdown and JSON reports from recon results.
"""
import json
import os
from datetime import datetime
from typing import Any

from .base import BaseModule
from .. import __version__


class ReportGenerator(BaseModule):
    name = "report_generator"
    description = "Report Generation"
    mode = "both"

    async def run(self, all_results: dict) -> dict:
        """Generate reports from all module results."""
        target = all_results.get("target", "unknown")
        mode = all_results.get("mode", "unknown")
        findings = all_results.get("findings", [])
        
        # Generate markdown report
        md_report = self._generate_markdown(target, mode, all_results, findings)
        
        # Generate JSON report
        json_report = self._generate_json(target, mode, all_results, findings)
        
        return {
            "module": self.name,
            "target": target,
            "findings": [],
            "data": {
                "markdown": md_report,
                "json": json_report,
            },
        }

    def _generate_markdown(self, target: str, mode: str, results: dict, findings: list) -> str:
        """Generate markdown report."""
        now = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
        
        # Count findings by severity
        severity_counts = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
        for f in findings:
            sev = f.get("severity", "info").lower()
            severity_counts[sev] = severity_counts.get(sev, 0) + 1

        md = f"""# Recon Framework Report

**Target:** `{target}`  
**Mode:** {mode.upper()}  
**Date:** {now}  
**Generated by:** Recon Framework v{__version__}

---

## Executive Summary

| Severity | Count |
|----------|-------|
| 🔴 Critical | {severity_counts['critical']} |
| 🟠 High | {severity_counts['high']} |
| 🟡 Medium | {severity_counts['medium']} |
| 🔵 Low | {severity_counts['low']} |
| ⚪ Info | {severity_counts['info']} |
| **Total** | **{sum(severity_counts.values())}** |

---

## Findings

"""

        # Sort findings by severity
        severity_order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
        sorted_findings = sorted(findings, key=lambda x: severity_order.get(x.get("severity", "info").lower(), 5))

        for i, finding in enumerate(sorted_findings, 1):
            sev = finding.get("severity", "info").upper()
            title = finding.get("title", "")
            detail = finding.get("detail", "")
            evidence = finding.get("evidence", "")
            
            icon = {"CRITICAL": "🔴", "HIGH": "🟠", "MEDIUM": "🟡", "LOW": "🔵", "INFO": "⚪"}.get(sev, "⚪")
            
            md += f"### {icon} {i}. [{sev}] {title}\n\n"
            if detail:
                md += f"{detail}\n\n"
            if evidence:
                if isinstance(evidence, list):
                    md += "**Evidence:**\n```\n"
                    for item in evidence[:20]:
                        md += f"{item}\n"
                    md += "```\n\n"
                elif isinstance(evidence, dict):
                    md += f"**Evidence:**\n```json\n{json.dumps(evidence, indent=2, default=str)[:2000]}\n```\n\n"
                else:
                    md += f"**Evidence:**\n```\n{str(evidence)[:2000]}\n```\n\n"

        # Subdomains section
        subdomains = results.get("cert_transparency", {}).get("data", {}).get("subdomains", [])
        if subdomains:
            md += f"\n---\n\n## Subdomains ({len(subdomains)})\n\n"
            md += "```\n"
            for sub in subdomains:
                md += f"{sub}\n"
            md += "```\n"

        # Open ports section
        ports = results.get("port_scan", {}).get("data", {}).get("open_ports", [])
        if ports:
            md += f"\n---\n\n## Open Ports ({len(ports)})\n\n"
            md += "| Port | Service |\n|------|--------|\n"
            for p in ports:
                md += f"| {p.get('port', '')} | {p.get('service', '')} |\n"

        # Technology stack
        tech = results.get("tech_fingerprint", {}).get("data", {}).get("technologies", [])
        if tech:
            md += f"\n---\n\n## Technology Stack\n\n"
            md += ", ".join(tech)
            md += "\n"

        # Top assets by rank
        ranked = results.get("asset_ranker", {}).get("data", {}).get("top_targets", [])
        if ranked:
            md += f"\n---\n\n## Top Targets (Ranked by Exploitability)\n\n"
            md += "| Rank | Score | Path |\n|------|-------|------|\n"
            for i, asset in enumerate(ranked[:15], 1):
                md += f"| {i} | {asset.get('score', 0)}/5 | `{asset.get('path', '')}` |\n"

        # Discovered endpoints
        endpoints = results.get("endpoint_probe", {}).get("data", {}).get("discovered", [])
        if endpoints:
            md += f"\n---\n\n## Discovered Endpoints ({len(endpoints)})\n\n"
            md += "| Path | Status | Label |\n|------|--------|-------|\n"
            for ep in endpoints[:30]:
                md += f"| `{ep.get('path', '')}` | {ep.get('status', '')} | {ep.get('label', '')} |\n"

        # Directory findings
        dirs = results.get("dir_bruteforce", {}).get("data", {}).get("found", [])
        if dirs:
            md += f"\n---\n\n## Discovered Directories ({len(dirs)})\n\n"
            md += "| Path | Status | Title |\n|------|--------|-------|\n"
            for d in dirs[:30]:
                md += f"| `{d.get('path', '')}` | {d.get('status', '')} | {d.get('title', '')[:50]} |\n"

        # JS findings
        js_secrets = results.get("js_analyzer", {}).get("data", {}).get("secrets", [])
        if js_secrets:
            md += f"\n---\n\n## JavaScript Secrets ({len(js_secrets)})\n\n"
            for secret in js_secrets[:10]:
                md += f"- **{secret.get('type', '')}**: `{secret.get('value', '')}` (in {secret.get('source', '')})\n"
            md += "\n"

        md += f"\n---\n\n*Report generated by Recon Framework v{__version__} on {now}*\n"
        
        return md

    def _generate_json(self, target: str, mode: str, results: dict, findings: list) -> dict:
        """Generate JSON report."""
        return {
            "metadata": {
                "tool": "Recon Framework",
                "version": __version__,
                "target": target,
                "mode": mode,
                "timestamp": datetime.utcnow().isoformat(),
            },
            "summary": {
                "total_findings": len(findings),
                "by_severity": {
                    sev: len([f for f in findings if f.get("severity", "").lower() == sev])
                    for sev in ["critical", "high", "medium", "low", "info"]
                },
            },
            "findings": findings,
            "modules": {
                name: {
                    "findings_count": len(data.get("findings", [])),
                    "data_keys": list(data.get("data", {}).keys()),
                }
                for name, data in results.items()
                if isinstance(data, dict) and name not in ("target", "mode", "findings")
            },
            "subdomains": results.get("cert_transparency", {}).get("data", {}).get("subdomains", []),
            "open_ports": results.get("port_scan", {}).get("data", {}).get("open_ports", []),
            "technologies": results.get("tech_fingerprint", {}).get("data", {}).get("technologies", []),
            "ranked_assets": results.get("asset_ranker", {}).get("data", {}).get("ranked_assets", []),
        }
